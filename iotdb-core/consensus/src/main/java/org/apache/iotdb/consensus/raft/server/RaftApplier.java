package org.apache.iotdb.consensus.raft.server;

import org.apache.iotdb.common.rpc.thrift.TSStatus;
import org.apache.iotdb.consensus.IStateMachine;
import org.apache.iotdb.consensus.common.request.ByteBufferConsensusRequest;
import org.apache.iotdb.consensus.common.request.IConsensusRequest;
import org.apache.iotdb.consensus.common.request.StateMachineApplyResult;
import org.apache.iotdb.consensus.common.research.ResearchMetrics;
import org.apache.iotdb.consensus.raft.core.action.Action;
import org.apache.iotdb.consensus.raft.core.event.Event;
import org.apache.iotdb.consensus.raft.core.log.LogEntry;
import org.apache.iotdb.consensus.raft.storage.LogStore;
import org.apache.iotdb.rpc.RpcUtils;
import org.apache.iotdb.rpc.TSStatusCode;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;

/**
 * Applies committed entries to the state machine on the group's apply executor, in the order the
 * Apply ranges are issued. Leader-ingested entries carry the live request (no deserialization);
 * replicated ones are deserialized and marked as generated by a remote leader.
 *
 * <p>An in-order profile (Raft) issues monotone ranges, and the applier never replays an index at
 * or below the last one it applied: queued application cannot replay what a snapshot install
 * already covers. An out-of-order profile (ParallelRaft) issues ranges in dependency order, so a
 * later range may lie below an earlier one by design (its apply policy issues an entry once no
 * unapplied predecessor conflicts with it): for it the applier executes every issued range and
 * skips only the indexes the installed snapshot covers.
 *
 * <p>A committed entry that cannot be read (missing from the store, or an I/O error) stops the
 * applier for good: no later Apply runs, since the state machine would otherwise skip the entry and
 * go on with a hole. A failed snapshot load stops it the same way ({@link #stopAfterFailedLoad}).
 * The failure is logged, kept ({@link #failure()}) and reported once to the failure handler (the
 * group server stops the group).
 *
 * <p>Batched application ({@link #setBatch}; the group server turns it on unless raft_apply_batch
 * is false): consecutive data entries of an Apply range go to the state machine with one {@link
 * IStateMachine#writeBatch} call, so per-call work is shared, and are then completed in index
 * order. Control and L0 file entries apply on their own. The first unsuccessful status stops the
 * applier as a failed single write does; the entries before it complete normally (the state machine
 * may already hold later entries of the run, as TRaft's batched application accepts: the group
 * stops and is rebuilt from its snapshot and log). If the batch call itself throws, no entry of the
 * run completes and the applier stops at its first.
 */
public class RaftApplier {

  private static final Logger LOGGER = LoggerFactory.getLogger(RaftApplier.class);

  private final String name;
  private final LogStore store;
  protected final IStateMachine stateMachine;
  private final ClientRequestTable requests;
  private final GroupExecutor applyExecutor;
  private final Consumer<Event> sink;
  private final Consumer<Throwable> onFailure;

  /** The profile issues Apply ranges out of index order (ParallelRaft). */
  private final boolean outOfOrder;

  /** Why the applier stopped (null while it runs); written and read on the apply executor. */
  private volatile Throwable failure;

  /**
   * Indexes at or below this are never (re)applied. In-order profile: the running applied frontier,
   * moved by every applied entry and by {@link #installedSnapshot}. Out-of-order profile: the
   * boundary of the snapshot the state machine loaded, moved by {@link #installedSnapshot} only.
   */
  private volatile long appliedThrough = -1;

  private volatile long appliedIndex = -1;
  protected volatile long l0AppliedBatches;

  /** At most this many entries per writeBatch call. */
  private static final int MAX_BATCH = 1024;

  private volatile boolean batch;

  public long appliedIndex() {
    return appliedIndex;
  }

  public long l0AppliedBatches() {
    return l0AppliedBatches;
  }

  public void resetAppliedIndex(long index) {
    installedSnapshot(index);
  }

  public RaftApplier(
      String name,
      LogStore store,
      IStateMachine stateMachine,
      ClientRequestTable requests,
      GroupExecutor applyExecutor,
      Consumer<Event> sink) {
    this(name, store, stateMachine, requests, applyExecutor, sink, t -> {});
  }

  /** An in-order applier: ranges below the last applied index are never replayed. */
  public RaftApplier(
      String name,
      LogStore store,
      IStateMachine stateMachine,
      ClientRequestTable requests,
      GroupExecutor applyExecutor,
      Consumer<Event> sink,
      Consumer<Throwable> onFailure) {
    this(name, store, stateMachine, requests, applyExecutor, sink, onFailure, false);
  }

  /**
   * @param outOfOrder the profile commits and issues Apply ranges out of index order: every issued
   *     range is executed, only the indexes the installed snapshot covers are skipped
   */
  public RaftApplier(
      String name,
      LogStore store,
      IStateMachine stateMachine,
      ClientRequestTable requests,
      GroupExecutor applyExecutor,
      Consumer<Event> sink,
      Consumer<Throwable> onFailure,
      boolean outOfOrder) {
    this.name = name;
    this.store = store;
    this.stateMachine = stateMachine;
    this.requests = requests;
    this.applyExecutor = applyExecutor;
    this.sink = sink;
    this.onFailure = onFailure;
    this.outOfOrder = outOfOrder;
  }

  public void enqueue(Action.Apply a) {
    applyExecutor.execute(() -> applyRange(a.fromInclusive, a.toInclusive));
  }

  /** raft_apply_batch: hand runs of data entries to the state machine at once. */
  public void setBatch(boolean enabled) {
    batch = enabled;
  }

  /** Why the applier stopped, or null if it runs. */
  public Throwable failure() {
    return failure;
  }

  /** Called while application is serialized with snapshot restoration. */
  public void installedSnapshot(long index) {
    appliedThrough = index;
    appliedIndex = index;
  }

  private void applyRange(long from, long to) {
    if (failure != null) {
      return; // stopped at a committed entry it could not read: nothing after it may be applied
    }
    List<LogEntry> run = new ArrayList<>();
    List<IConsensusRequest> runRequests = new ArrayList<>();
    for (long i = Math.max(from, appliedThrough + 1); i <= to; i++) {
      LogEntry e;
      try {
        e = store.read(i);
      } catch (IOException ex) {
        if (applyRun(run, runRequests)) {
          stop(i, new IOException(name + ": cannot read committed entry " + i, ex));
        }
        return;
      }
      if (e == null) {
        if (applyRun(run, runRequests)) {
          stop(
              i,
              new IllegalStateException(
                  name + ": committed entry " + i + " is missing from the log"));
        }
        return;
      }
      if (batch && !e.type.isControl() && !isSpecialEntry(e)) {
        IConsensusRequest request;
        try {
          request = prepare(e);
        } catch (Throwable failure) {
          if (applyRun(run, runRequests)) {
            stop(i, failure);
          }
          return;
        }
        run.add(e);
        runRequests.add(request);
        if (run.size() >= MAX_BATCH && !applyRun(run, runRequests)) {
          return;
        }
        continue;
      }
      if (!applyRun(run, runRequests)) {
        return;
      }
      TSStatus status;
      try {
        status = applyOne(e);
        StateMachineApplyResult.requireCompleted(status);
      } catch (Throwable failure) {
        stop(i, failure);
        return;
      }
      completed(e, status);
    }
    applyRun(run, runRequests);
  }

  /**
   * Writes a run of data entries with one writeBatch call and completes them in index order.
   * Returns false if the applier stopped at one of them; the lists are cleared either way.
   */
  private boolean applyRun(List<LogEntry> run, List<IConsensusRequest> runRequests) {
    if (run.isEmpty()) {
      return true;
    }
    try {
      List<TSStatus> statuses;
      try {
        statuses = stateMachine.writeBatch(runRequests);
        if (statuses == null || statuses.size() != runRequests.size()) {
          throw new IllegalStateException(
              name
                  + ": the state machine returned "
                  + (statuses == null ? "no" : String.valueOf(statuses.size()))
                  + " results for "
                  + runRequests.size()
                  + " requests");
        }
      } catch (Throwable failure) {
        stop(run.get(0).index, failure);
        return false;
      }
      ResearchMetrics.add("raft.apply_batch_count", 1);
      ResearchMetrics.add("raft.apply_batch_entries", run.size());
      for (int k = 0; k < run.size(); k++) {
        LogEntry e = run.get(k);
        TSStatus status = statuses.get(k);
        try {
          StateMachineApplyResult.requireCompleted(status);
        } catch (Throwable failure) {
          stop(e.index, failure);
          return false;
        }
        completed(e, status);
      }
      return true;
    } finally {
      run.clear();
      runRequests.clear();
    }
  }

  private void completed(LogEntry e, TSStatus status) {
    requests.onApplied(e.index, e.term, status);
    if (!outOfOrder) {
      appliedThrough = e.index;
    }
    appliedIndex = Math.max(appliedIndex, e.index);
    sink.accept(new Event.Applied(e.index, status));
  }

  private void stop(long index, Throwable cause) {
    failure = cause;
    LOGGER.error(
        "{}: the applier stops before committed entry {}; no later entry is applied",
        name,
        index,
        cause);
    report(cause);
  }

  /**
   * A snapshot load failed on the apply executor: the state machine may have lost what it held, so
   * nothing queued behind the load may run on it.
   */
  public void stopAfterFailedLoad(Throwable cause) {
    failure = cause;
    LOGGER.error("{}: the applier stops after a failed snapshot load", name, cause);
    report(cause);
  }

  private void report(Throwable cause) {
    try {
      onFailure.accept(cause);
    } catch (RuntimeException e) {
      LOGGER.error("{}: the applier's failure handler failed", name, e);
    }
  }

  protected TSStatus applyOne(LogEntry e) throws IOException {
    if (e.type.isControl()) {
      return RpcUtils.getStatus(TSStatusCode.SUCCESS_STATUS);
    }

    return stateMachine.write(prepare(e));
  }

  /** The state machine request of a data entry, marked when a remote leader generated it. */
  private IConsensusRequest prepare(LogEntry e) {
    boolean local =
        e.liveRequest instanceof IConsensusRequest || requests.isLocalEntry(e.index, e.term);
    IConsensusRequest raw =
        e.liveRequest instanceof IConsensusRequest
            ? (IConsensusRequest) e.liveRequest
            : new ByteBufferConsensusRequest(e.payload());
    IConsensusRequest request = stateMachine.deserializeRequest(raw);
    if (!local) {
      request.markAsGeneratedByRemoteConsensusLeader();
    }
    return request;
  }

  protected boolean isSpecialEntry(LogEntry entry) {
    return false;
  }
}
