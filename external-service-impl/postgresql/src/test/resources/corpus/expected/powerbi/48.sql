SELECT "typ"."oid", "att"."attname", "att"."atttypid" FROM information_schema."pg_type" AS "typ" JOIN information_schema."pg_namespace" AS "ns" ON ("ns"."oid" = "typ"."typnamespace") JOIN information_schema."pg_class" AS "cls" ON ("cls"."oid" = "typ"."typrelid") JOIN information_schema."pg_attribute" AS "att" ON ("att"."attrelid" = "typ"."typrelid") WHERE ("typ"."typtype" = 'c' AND "cls"."relkind" = 'c') AND "attnum" > 0 AND NOT "attisdropped" ORDER BY "typ"."oid" NULLS LAST, "att"."attnum" NULLS LAST
